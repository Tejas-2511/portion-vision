# Fallback density when food name is not found
DEFAULT_DENSITY = 1.0  # g/ml (approximately water density)


def get_density(food_name: str) -> float:
    """
    Lookup density for a food item.
    Tries exact match first, then substring match, then returns default.
    """
    key = food_name.strip().lower()

    if key in FOOD_DENSITIES:
        return FOOD_DENSITIES[key]

    for name, density in FOOD_DENSITIES.items():
        if name in key or key in name:
            return density

    return DEFAULT_DENSITY


def get_dynamic_density(
    food_name: str,
    mask_region_bgr: np.ndarray | None = None,
) -> float:
    """
    Enhancement #6 — Dynamic density adjustment based on visual features.

    Extracts brightness, saturation, and texture from the food's pixel region
    and adjusts the base density accordingly.  Falls back to get_density()
    if mask_region_bgr is not provided or too small.

    Args:
        food_name:        Canonical food name.
        mask_region_bgr:  BGR crop of just the food pixels (can contain grey
                          background outside the mask — see classifier.py).
                          Pass None to use static density.

    Returns:
        Adjusted density in g/ml.
    """
    base_density = get_density(food_name)

    if mask_region_bgr is None or mask_region_bgr.size < 100:
        return base_density

    try:
        hsv = cv2.cvtColor(mask_region_bgr, cv2.COLOR_BGR2HSV).astype(np.float32)
        mean_brightness = float(np.mean(hsv[:, :, 2]))   # 0–255
        mean_saturation = float(np.mean(hsv[:, :, 1]))   # 0–255

        gray    = cv2.cvtColor(mask_region_bgr, cv2.COLOR_BGR2GRAY).astype(np.float32)
        texture = float(np.var(cv2.Laplacian(gray, cv2.CV_32F)))

    except cv2.error:
        return base_density

    key = food_name.strip().lower()

    # ── Per-food visual continuous adjustment rules ───────────────────────────
    # Rice: bright (white/fluffy) = less packed, darker/compact = more packed
    if "rice" in key or "chawal" in key or "pulao" in key or "khichdi" in key:
        # Normalize brightness: 130 (dark/compact) -> 220 (light/fluffy)
        b_norm = float(np.clip((mean_brightness - 130.0) / 90.0, 0.0, 1.0))
        # Dense (+0.08) down to fluffy (-0.12)
        adj = 0.08 - (0.20 * b_norm)
        return round(float(np.clip(base_density + adj, 0.75, 1.25)), 3)

    # Dal / sambar: higher texture & saturation = thicker dal tadka / dal makhani
    if "dal" in key or "daal" in key or "sambar" in key or "rasam" in key:
        # Thin watery dal is close to 1.00 g/ml; thick dal makhani is ~1.12 g/ml
        t_norm = float(np.clip(texture / 300.0, 0.0, 1.0))
        s_norm = float(np.clip(mean_saturation / 180.0, 0.0, 1.0))
        adj = (0.05 * t_norm) + (0.04 * s_norm) - 0.04
        return round(float(np.clip(base_density + adj, 0.95, 1.15)), 3)

    # Sabzi / curries: chunky vegetable pieces with gravy
    if any(k in key for k in ("sabzi", "sabji", "gobi", "aloo", "chicken", "paneer", "curry")):
        t_norm = float(np.clip(texture / 400.0, 0.0, 1.0))
        adj = (t_norm - 0.5) * 0.12
        return round(float(np.clip(base_density + adj, 0.80, 1.15)), 3)

    # Roti / chapati: fresh puffed vs dense dry flatbread
    if any(k in key for k in ("roti", "chapati", "naan", "paratha")):
        t_norm = float(np.clip(texture / 600.0, 0.0, 1.0))
        adj = -0.06 * t_norm
        return round(float(np.clip(base_density + adj, 0.70, 0.95)), 3)

    return round(float(base_density), 3)
